#include "mirrortest/backend/hook_header.h"

#include <initializer_list>
#include <string>
#include <vector>

#include "mirrortest/core/naming.h"

namespace mt::backend {

namespace {

void add(std::vector<std::string>& lines, std::initializer_list<const char*> more) {
    for (const char* line : more) lines.push_back(line);
}

}  // namespace

std::string hook_header(const core::Config& config, const std::string& source) {
    const bool aborts = config.no_exceptions || config.no_stl;
    const std::string guard = core::include_guard(kHookHeaderName);

    std::vector<std::string> lines;
    if (!config.file_header.empty()) lines.push_back(config.file_header);
    lines.push_back("// Generated by mirrortest" + (source.empty() ? std::string() : " from " + source) + ". Review every TODO(mt).");
    if (config.guard == core::GuardStyle::PragmaOnce) {
        lines.push_back("#pragma once");
    } else {
        lines.push_back("#ifndef " + guard);
        lines.push_back("#define " + guard);
    }
    lines.push_back("");
    if (aborts) {
        add(lines, {"#include <cstdio>", "#include <cstdlib>"});
    } else {
        add(lines, {"#include <stdexcept>", "#include <string>"});
    }
    lines.push_back("");
    add(lines, {"// What a stub does while the code it stands for is not written (stub_policy \"hook\"): it calls",
                "// mt_not_implemented() with its signature."});
    lines.push_back(aborts ? "// The default handler prints the signature and aborts."
                           : "// The default handler throws a std::logic_error that says which signature.");
    add(lines, {"//",
                "// To let the other tests run (QTest ends the program at the first exception), set a handler that makes",
                "// the running test fail and returns, before the tests start: QTest::qFail(...), ADD_FAILURE(), ...",
                "//",
                "//     mt_set_not_implemented_handler(&my_handler);",
                "//",
                "// The stub then returns an empty value and the test goes on. A handler that returns without failing",
                "// the test lets it pass without the code it tests.",
                "typedef void (*mt_not_implemented_handler)(const char* signature);",
                "",
                "inline void mt_default_not_implemented_handler(const char* signature) {"});
    if (aborts) {
        add(lines, {"    std::fprintf(stderr, \"mirrortest: not implemented: %s\\n\", signature);", "    std::abort();"});
    } else {
        lines.push_back("    throw std::logic_error(std::string(\"mirrortest: not implemented: \") + signature);");
    }
    add(lines, {"}",
                "",
                "inline mt_not_implemented_handler& mt_current_not_implemented_handler() {",
                "    static mt_not_implemented_handler current = &mt_default_not_implemented_handler;",
                "    return current;",
                "}",
                "",
                "// Sets the handler (nullptr puts the default back) and returns the one it replaces.",
                "inline mt_not_implemented_handler mt_set_not_implemented_handler(mt_not_implemented_handler handler) {",
                "    mt_not_implemented_handler& current = mt_current_not_implemented_handler();",
                "    const mt_not_implemented_handler previous = current;",
                "    current = handler != nullptr ? handler : &mt_default_not_implemented_handler;",
                "    return previous;",
                "}",
                "",
                "inline void mt_not_implemented(const char* signature) {",
                "    mt_current_not_implemented_handler()(signature);",
                "}"});
    if (config.guard != core::GuardStyle::PragmaOnce) {
        lines.push_back("");
        lines.push_back("#endif  // " + guard);
    }

    std::string text;
    for (const std::string& line : lines) text += line + "\n";
    return text;
}

}  // namespace mt::backend
